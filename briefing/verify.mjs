import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';

const root = dirname(fileURLToPath(import.meta.url));
const require = createRequire(join(process.env.HALLMARK_PUPPETEER || root, 'package.json'));
const puppeteer = require('puppeteer-core');
const out = join(root, '.qa');
await mkdir(out, {recursive: true});
const browser = await puppeteer.launch({executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true});
const checks = [];
const errors = [];
const check = (name, condition) => { assert.ok(condition, name); checks.push(name); };
try {
  const page = await browser.newPage();
  page.on('pageerror', (error) => errors.push(error.message));
  await page.emulateMediaFeatures([{name: 'prefers-reduced-motion', value: 'reduce'}]);
  await page.setViewport({width: 1440, height: 900});
  await page.goto(pathToFileURL(join(root, 'index.html')).href, {waitUntil: 'load'});
  await page.evaluate(() => document.fonts.ready);
  check('nine readable chapters', await page.$$eval('.chapter', (items) => items.length === 9 && items.every((el) => el.innerText.length > 30)));
  check('offline serif loaded', await page.evaluate(() => document.fonts.check('700 60px "Noto Serif SC"', '让人和')));
  check('all internal links resolve', await page.$$eval('a[href^="#"]', (links) => links.every((a) => !!document.getElementById(a.hash.slice(1)))));
  await page.click('[data-run="1"]');
  check('Run switch preserves Task and changes explanation', await page.$eval('#continuity-note', (el) => el.textContent.includes('回复进入原 Task')));
  await page.click('#mapNext');
  check('map tour advances', await page.$eval('#mapCounter', (el) => el.textContent.includes('2 / 7')));
  await page.click('[data-node="harness"]');
  check('diagram node exploration shows responsibility', await page.$eval('#mapDetail', (el) => el.textContent.includes('业务 Harness') && el.textContent.includes('门禁')));
  await page.click('[data-space="project"]');
  check('space switch changes ownership context', await page.$eval('#spaceFacts', (el) => el.textContent.includes('项目成员')));
  await page.click('[data-space="project"]');
  await page.keyboard.press('ArrowLeft');
  check('tabs support keyboard selection', await page.$eval('[data-space="personal"]', (el) => el.getAttribute('aria-selected') === 'true'));
  await page.click('#shareGoal'); await page.click('#shareReport');
  check('empty sharing selection exposes empty state', await page.$eval('#shareResult', (el) => el.textContent.includes('未选择内容')));
  await page.click('[data-object="run"]');
  check('object detail opens accessible dialog', await page.$eval('#objectDialog', (el) => el.open && el.textContent.includes('不自动代表')));
  await page.keyboard.press('Escape');
  check('Escape closes object dialog', await page.$eval('#objectDialog', (el) => !el.open));
  await page.click('[data-story="4"]');
  check('Run success does not complete Task', await page.evaluate(() => document.querySelector('#storyRun').textContent.includes('成功') && document.querySelector('#storyTask').textContent.includes('待验收')));
  await page.keyboard.press('ArrowRight');
  check('story supports arrow navigation', await page.$eval('#storyTitle', (el) => el.textContent.includes('报送')));
  await page.click('[data-story="6"]');
  check('final story state is explicitly a simulation', await page.$eval('#storyTask', (el) => el.textContent === '已完成（演示）'));
  await page.click('#storyReset');
  check('story reset restores initial state', await page.$eval('#storyTask', (el) => el.textContent.includes('未开始')));
  await page.click('[data-executor="matrix"]');
  check('Matrix remains a distinct execution mechanism', await page.$eval('#executorDetail', (el) => el.textContent.includes('独立团队执行体系')));
  await page.click('#rollbackBtn');
  check('rollback retains history and invalidates prior evidence', await page.$eval('#phaseHistory', (el) => el.children.length === 4 && el.textContent.includes('重新评估')));
  check('rollback creates human wait on same Task', await page.$eval('#phaseStatus', (el) => el.textContent.includes('Task 待确认，阶段 N1')));
  await page.click('#phaseReset');
  check('phase reset works', await page.$eval('#phaseHistory', (el) => el.children.length === 2));
  await page.click('[data-route="candidate"]');
  check('proactive work defaults to observation', await page.$eval('#routeTitle', (el) => el.textContent.includes('默认观察')));
  await page.click('[data-roadmap="1"]');
  check('roadmap flags cross-device work as future validation', await page.$eval('#roadmapProof', (el) => el.textContent.includes('仍需验证')));
  await page.click('#notesBtn');
  check('presenter notes toggle', await page.$eval('.speaker', (el) => getComputedStyle(el).display !== 'none'));
  await page.click('#notesBtn');
  await page.click('#focusBtn');
  check('immersive mode opens', await page.evaluate(() => document.body.classList.contains('immersive')));
  await page.keyboard.press('Escape');
  check('immersive mode can be exited by keyboard', await page.evaluate(() => !document.body.classList.contains('immersive')));
  await page.click('#themeBtn');
  check('dark theme changes palette', await page.evaluate(() => document.documentElement.dataset.theme === 'dark'));
  await page.evaluate(() => document.querySelector('#panorama').scrollIntoView());
  await page.screenshot({path: join(out, 'dark-panorama.png')});
  await page.click('#themeBtn');
  for (const width of [320, 375, 768, 1280, 1440, 1920]) {
    await page.setViewport({width, height: width < 800 ? 900 : 1000});
    await page.evaluate(() => scrollTo(0, 0));
    const layout = await page.evaluate(() => ({viewport: innerWidth, content: document.documentElement.scrollWidth, clippedButtons: [...document.querySelectorAll('button')].filter((el) => el.getBoundingClientRect().width > 0 && el.scrollWidth > el.clientWidth + 2).map((el) => el.textContent.trim())}));
    check(`no horizontal overflow at ${width}`, layout.content <= layout.viewport && layout.clippedButtons.length === 0);
  }
  await page.setViewport({width: 375, height: 900});
  await page.click('#menuBtn');
  check('mobile chapter menu opens', await page.$eval('#menuBtn', (el) => el.getAttribute('aria-expanded') === 'true'));
  await page.click('#toc a[href="#story"]');
  check('mobile selection closes menu', await page.$eval('#menuBtn', (el) => el.getAttribute('aria-expanded') === 'false'));
  await page.screenshot({path: join(out, 'mobile-story.png')});
  await page.click('.node-index [data-node="people"]');
  const humanColor = await page.$eval('.node-index [data-node="people"]', (el) => getComputedStyle(el).color);
  await page.click('.node-index [data-node="artifact"]');
  const deliveryColor = await page.$eval('.node-index [data-node="artifact"]', (el) => getComputedStyle(el).color);
  check('mobile diagram preserves semantic color distinction', humanColor !== deliveryColor);
  await page.screenshot({path: join(out, 'mobile-panorama.png')});
  await page.setViewport({width: 1440, height: 1000});
  for (const id of ['overview', 'panorama', 'spaces', 'story', 'executors', 'harness', 'architecture', 'roadmap', 'alignment']) {
    await page.evaluate((id) => document.getElementById(id).scrollIntoView({block: 'start'}), id);
    await page.screenshot({path: join(out, `${id}.png`)});
  }
  await page.emulateMediaType('print');
  check('print reveals speaking notes', await page.$eval('.speaker', (el) => getComputedStyle(el).display === 'block'));
  check('print removes navigation', await page.$eval('.rail', (el) => getComputedStyle(el).display === 'none'));
  await page.emulateMediaType('screen');
  const standalone = await browser.newPage();
  const remoteRequests = [];
  standalone.on('request', (request) => { if (/^https?:/.test(request.url())) remoteRequests.push(request.url()); });
  standalone.on('pageerror', (error) => errors.push(error.message));
  await standalone.setOfflineMode(true);
  await standalone.goto(pathToFileURL(join(root, 'Cimi-Work-产品介绍与蓝图.html')).href, {waitUntil: 'load'});
  await standalone.evaluate(() => document.fonts.ready);
  await standalone.click('[data-story="4"]');
  check('single HTML works offline', await standalone.$eval('#storyTask', (el) => el.textContent.includes('待验收')));
  check('single HTML makes no network requests', remoteRequests.length === 0);
  const noJs = await browser.newPage();
  await noJs.setJavaScriptEnabled(false);
  await noJs.goto(pathToFileURL(join(root, 'Cimi-Work-产品介绍与蓝图.html')).href, {waitUntil: 'load'});
  check('core content remains readable without JavaScript', await noJs.$$eval('.chapter', (items) => items.length === 9 && items.every((el) => el.getBoundingClientRect().height > 100)));
  check('no browser runtime exceptions', errors.length === 0);
  const result = {passed: checks.length, checks, runtimeErrors: errors, offlineNetworkRequests: remoteRequests.length};
  await writeFile(join(out, 'verification.json'), JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result, null, 2));
} finally { await browser.close(); }
